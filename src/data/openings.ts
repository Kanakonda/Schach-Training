import type { Opening, Side } from '../lib/types'

type RawLine = [name: string, moves: string, idea: string]

function opening(
  id: string,
  name: string,
  eco: string,
  side: Side,
  description: string,
  lines: RawLine[],
): Opening {
  return {
    id,
    name,
    eco,
    side,
    description,
    lines: lines.map(([lineName, moves, idea], i) => ({
      id: `l${i + 1}`,
      name: lineName,
      idea,
      moves: moves.split(' '),
    })),
  }
}

